package com.peopletech.vo;

public class CpuSummaryVO {
    private String overallScore;
    private String ranking;
    private String performanceNote;
    private String efficiencyNote;
    private String thermalsNote;

    public String getOverallScore() { return overallScore; } public void setOverallScore(String overallScore) { this.overallScore = overallScore; }
    public String getRanking() { return ranking; } public void setRanking(String ranking) { this.ranking = ranking; }
    public String getPerformanceNote() { return performanceNote; } public void setPerformanceNote(String performanceNote) { this.performanceNote = performanceNote; }
    public String getEfficiencyNote() { return efficiencyNote; } public void setEfficiencyNote(String efficiencyNote) { this.efficiencyNote = efficiencyNote; }
    public String getThermalsNote() { return thermalsNote; } public void setThermalsNote(String thermalsNote) { this.thermalsNote = thermalsNote; }
}
